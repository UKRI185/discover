# Settings --------------------------------------------------------------
required <- c("mya", "title", "image", "caption", "license", "body",
              "contributor", "eon", "era", "period", "colour")

licences <- c(
  "CC BY-SA 4.0" = "https://creativecommons.org/licenses/by-sa/4.0/deed.en",
  "CC BY 4.0" = "https://creativecommons.org/licenses/by/4.0/deed.en",
  "CC BY 3.0" = "https://creativecommons.org/licenses/by/3.0/deed.en",
  "CC0 1.0" = "https://creativecommons.org/publicdomain/zero/1.0/deed.en"
)

# Helpers ---------------------------------------------------------------
html_escape <- function(x) {
  x <- gsub("&", "&amp;", x, fixed = TRUE)
  x <- gsub("<", "&lt;", x, fixed = TRUE)
  x <- gsub(">", "&gt;", x, fixed = TRUE)
  gsub('"', "&quot;", x, fixed = TRUE)
}

link_license <- function(x) {
  for (nm in names(licences)) {
    link <- sprintf("<a href='%s' target='_blank' rel='noopener'>%s</a>",
                    licences[[nm]], nm)
    x <- gsub(nm, link, x, fixed = TRUE)
  }
  x
}

# Body paragraphs are separated by "||". The contributor is appended to the
# last paragraph, and an eon/era/period tag line is added (blank levels
# omitted).
make_detail <- function(title, body, contributor, eon, era, period) {
  paras <- trimws(strsplit(body, "||", fixed = TRUE)[[1]])
  paras <- paras[nzchar(paras)]
  if (length(paras) == 0) paras <- ""
  if (nzchar(contributor)) {
    last <- length(paras)
    paras[last] <- paste0(paras[last], "<br><br>Contributed by: ", contributor)
  }
  tags <- c(Eon = eon, Era = era, Period = period)
  tags <- tags[nzchar(tags)]
  etag <- if (length(tags) > 0) {
    sprintf('<p class="etag">%s</p>',
            paste0(names(tags), ": ", tags, collapse = " \u00b7 "))
  } else ""
  paste(paste0("<h3>", html_escape(title), "</h3>"),
        paste0("<p>", paras, "</p>", collapse = " "),
        etag)
}

# Wrangle file ----------------------------------------------------------
events <- read.csv("events.csv", colClasses = "character", na.strings = "",
                   check.names = FALSE, encoding = "UTF-8")
missing <- setdiff(required, names(events))
if (length(missing) > 0) {
  stop("events.csv is missing column(s): ", paste(missing, collapse = ", "))
}
events[is.na(events)] <- ""
events[] <- lapply(events, trimws)

events$mya <- as.numeric(events$mya)
if (anyNA(events$mya)) stop("Non-numeric value(s) in 'mya' column.")
events <- events[order(-events$mya), ]  # oldest first

events$image <- ifelse(nzchar(events$image), paste0("images/", events$image), "")
events$caption <- trimws(paste0(
  events$caption,
  ifelse(nzchar(events$license),
         paste0(" License: ", link_license(events$license)), "")
))
events$detail <- mapply(make_detail, events$title, events$body,
                        events$contributor, events$eon, events$era,
                        events$period, USE.NAMES = FALSE)

# Build JS --------------------------------------------------------------
out <- data.frame(
  mya    = events$mya,
  title  = events$title,
  image  = events$image,
  cap    = events$caption,
  detail = events$detail,
  eon    = events$eon,
  era    = events$era,
  per    = events$period,
  colour = events$colour,
  stringsAsFactors = FALSE
)
# jsonlite handles all string escaping; digits = NA keeps full precision
json <- jsonlite::toJSON(out, auto_unbox = TRUE, pretty = TRUE, digits = NA)

dir.create("js", showWarnings = FALSE)
con <- file(file.path("js", "events.js"), open = "w", encoding = "UTF-8")
writeLines(c(
  "// AUTO-GENERATED by generate_events.R \u2014 do not edit by hand.",
  "// Edit events.csv and re-run:  Rscript generate_events.R",
  paste0("// Generated: ", format(Sys.time(), "%Y-%m-%d %H:%M")),
  "",
  paste0("const EVENTS = ", json, ";")
), con)
close(con)

cat(sprintf("\u2713 Written %d events to js/events.js\n", nrow(out)))